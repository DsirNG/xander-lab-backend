-- Agent Harness execution journal baseline. Apply after agent_conversation_migration.sql.
CREATE TABLE IF NOT EXISTS `agent_run` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '执行记录主键',
  `user_id` BIGINT NOT NULL COMMENT '所属用户ID，冗余保存以支持按用户审计与授权过滤',
  `conversation_id` BIGINT NOT NULL COMMENT '所属会话ID，关联 agent_conversation.id',
  `run_version` BIGINT NOT NULL COMMENT '会话执行代次；同一会话内唯一，对应一次成功领取',
  `intent_epoch` CHAR(36) NULL COMMENT '用户意图周期标识(UUID)：一次用户诉求一个周期。claim() 铸新的，resume() 复用旧的——这是“同一件事的重试”与“新的一件事”的分界。不参与 run_version 的递增逻辑，两者正交',
  `status` VARCHAR(24) NOT NULL COMMENT '运行状态（权威，九态）：CREATED已落库未开始（尚无生产者）/RUNNING执行中/WAITING_APPROVAL有具体调用等待属主决定/PAUSED用户主动暂停（尚无生产者）/INTERRUPTED持有者进程消失未收口/BUDGET_EXHAUSTED预算耗尽可继续/COMPLETED正常收口/CANCELLED用户请求停止后收口/FAILED异常收口；终态只有 COMPLETED/CANCELLED/FAILED，terminal→不再迁移',
  `intent_json` LONGTEXT NULL COMMENT '当轮技能路由机制快照（JSON）：记录“怎么决定的”而非“决定了什么”，如 {"routing":"model-loaded-catalog","catalogSize":N}。服务端已不再按关键词猜意图，故不含置信度；不得保存原始用户提示词',
  `skills_json` LONGTEXT NULL COMMENT '当轮技能供给快照（JSON）：目录里提供了哪些技能(id/version/source)与当时的工具表。用于排查“模型当时能读到哪些技能”',
  `execution_snapshot_json` LONGTEXT NULL COMMENT '当轮技能供给规模摘要（JSON）：{"catalogSize":N,"toolCount":M}。早期注释称其为“模型路由与预算快照”，实际从未如此——预算快照见 budget_json',
  `budget_json` LONGTEXT NULL COMMENT '本轮冻结的资源上限快照（RunBudget 的 JSON）。claim 那一刻由配置折算写入，整个 Run 只读它；运行期改配置不得影响已开始的 Run，否则“这次为什么超预算”无法复现',
  `auto_resumed_at` DATETIME NULL COMMENT '最近一次被调度器自动 resume 的时间；非空表示“这个Run已经自动恢复过一次”。安全阀：再崩不再自动重试（防止坏工具导致无限循环），由运维或用户显式介入',
  `active_duration_ms` BIGINT NOT NULL DEFAULT 0 COMMENT '累计活跃时长(毫秒)：只累加RUNNING期间，等待审批/暂停/中断期间不累加。按墙钟算会让“10:00发起、10:01转待审批、13:00批准”的Run在恢复瞬间就判超时，而它实际只跑了一分钟',
  `last_running_at` DATETIME NULL COMMENT '最近一次进入RUNNING的时刻(UTC)；离开RUNNING或崩溃恢复时用它结算一段活跃时长并置NULL。非NULL表示“此刻正在RUNNING”',
  `failure_reason` VARCHAR(1000) NULL COMMENT '失败收口的安全摘要，不保存调用栈或凭据',
  `started_at` DATETIME NOT NULL COMMENT '运行领取成功后的开始时间',
  `completed_at` DATETIME NULL COMMENT '运行进入终态的时间；执行中为空',
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '记录创建时间',
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '记录最后更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_agent_run_conversation_version` (`conversation_id`, `run_version`),
  KEY `idx_agent_run_user_created` (`user_id`, `created_at`),
  KEY `idx_agent_run_status_updated` (`status`, `updated_at`),
  CONSTRAINT `fk_agent_run_conversation` FOREIGN KEY (`conversation_id`)
    REFERENCES `agent_conversation` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_agent_run_user` FOREIGN KEY (`user_id`)
    REFERENCES `sys_user` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='智能体单轮执行事实日志';

CREATE TABLE IF NOT EXISTS `agent_step` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '步骤记录主键',
  `run_id` BIGINT NOT NULL COMMENT '所属执行记录ID，关联 agent_run.id',
  `step_no` INT NOT NULL COMMENT '本轮模型决策顺序，从1开始递增',
  `status` VARCHAR(24) NOT NULL COMMENT '步骤状态：RUNNING模型调用前已落意图/COMPLETED已得到决策/FAILED调用失败/CANCELLED用户取消',
  `request_snapshot_json` LONGTEXT NULL COMMENT '请求元数据快照，只含上下文长度、工具集合哈希和附件计数等非原始内容',
  `decision_json` LONGTEXT NULL COMMENT '模型解析后的结构化决策，供审计下一步工具或最终回复',
  `model_name` VARCHAR(160) NULL COMMENT '实际响应模型名称，未返回时为空',
  `input_tokens` BIGINT NOT NULL DEFAULT 0 COMMENT '本步骤模型输入Token数，网关未返回时为0',
  `cached_tokens` BIGINT NOT NULL DEFAULT 0 COMMENT '本步骤命中缓存的输入Token数，网关未返回时为0',
  `output_tokens` BIGINT NOT NULL DEFAULT 0 COMMENT '本步骤模型输出Token数，网关未返回时为0',
  `failure_reason` VARCHAR(1000) NULL COMMENT '步骤失败或取消的安全摘要',
  `started_at` DATETIME NOT NULL COMMENT '远端模型调用前的落库时间',
  `completed_at` DATETIME NULL COMMENT '步骤完成、失败或取消的时间',
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '记录创建时间',
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '记录最后更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_agent_step_run_number` (`run_id`, `step_no`),
  KEY `idx_agent_step_status_updated` (`status`, `updated_at`),
  CONSTRAINT `fk_agent_step_run` FOREIGN KEY (`run_id`) REFERENCES `agent_run` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='智能体模型决策步骤事实日志';

CREATE TABLE IF NOT EXISTS `agent_tool_invocation` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '工具调用记录主键',
  `run_id` BIGINT NOT NULL COMMENT '所属执行记录ID，关联 agent_run.id',
  `step_id` BIGINT NOT NULL COMMENT '触发该调用的模型步骤ID，关联 agent_step.id',
  `effect_id` CHAR(36) NULL COMMENT '所属逻辑副作用，关联 agent_effect.effect_id；只读工具为空。它是下游 client_request_id 的取值来源，与 invocation_id 不同层',
  `invocation_id` CHAR(36) NOT NULL COMMENT '工具调用稳定UUID，标识"这一次物理调用"；**不是**下游幂等键（那个是 effect_id，跨多次调用不变）',
  `tool_name` VARCHAR(64) NOT NULL COMMENT '已请求的注册工具名称',
  `arguments_json` LONGTEXT NULL COMMENT '模型提交给工具的结构化参数，仅限私有审计与恢复使用',
  `status` VARCHAR(24) NOT NULL COMMENT '调用状态：RUNNING执行中/SUCCEEDED已持久化结果/FAILED执行失败/CANCELLED用户取消/UNKNOWN进程中断后需对账',
  `effect_state` VARCHAR(16) NOT NULL DEFAULT 'NONE' COMMENT '副作用执行阶段：NONE未进入副作用路径(只读工具，或迁移前的存量行——**判读须连effect_id一起看**)/PREPARED意图已落库但请求尚未发出/DISPATCHED请求已交给工具(可能已在远端生效)/CONFIRMED已拿到远端成功凭据',
  `effect_dispatched_at` DATETIME NULL COMMENT '标记为DISPATCHED的时间。**必须写在把请求交给工具之前**：崩在"标记"与"发送"之间只会产生一个假DISPATCHED（多一次无谓对账，安全方向），反过来则会漏掉一次真实写入（要命方向）',
  `effect_confirmed_at` DATETIME NULL COMMENT '拿到远端成功凭据的时间；与 invocation 的SUCCEEDED同事务落库',
  `result_json` LONGTEXT NULL COMMENT '工具返回的标准化结构化结果',
  `error_message` VARCHAR(1000) NULL COMMENT '工具失败或取消的安全摘要，不保存堆栈',
  `started_at` DATETIME NOT NULL COMMENT '工具执行前意图持久化时间',
  `completed_at` DATETIME NULL COMMENT '工具结果、失败或取消的持久化时间',
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '记录创建时间',
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '记录最后更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_agent_tool_invocation_id` (`invocation_id`),
  KEY `idx_agent_tool_invocation_run_created` (`run_id`, `created_at`),
  KEY `idx_agent_tool_invocation_status_updated` (`status`, `updated_at`),
  KEY `idx_agent_tool_invocation_effect` (`effect_id`),
  CONSTRAINT `fk_agent_tool_invocation_run` FOREIGN KEY (`run_id`) REFERENCES `agent_run` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_agent_tool_invocation_step` FOREIGN KEY (`step_id`) REFERENCES `agent_step` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='智能体工具调用事实日志';

CREATE TABLE IF NOT EXISTS `agent_effect` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '逻辑副作用主键',
  `effect_id` CHAR(36) NOT NULL COMMENT '业务幂等身份(UUID)，Runtime 铸造；跨多次 invocation 保持不变，是下游 client_request_id 的取值来源。与 invocation_id 不同层：那个标识"这一次物理调用"，这个标识"这一个业务动作"',
  `user_id` BIGINT NOT NULL COMMENT '归属用户ID，与下游唯一键 (user_id, client_request_id) 对齐；冗余保存以支持按用户审计与授权过滤',
  `conversation_id` BIGINT NOT NULL COMMENT '所属会话ID，关联 agent_conversation.id',
  `run_id` BIGINT NOT NULL COMMENT '首次提出该副作用的执行记录ID，关联 agent_run.id；后续复用它的 invocation 属于同一个 Run（同 run_version、同 intent_epoch）',
  `intent_epoch` CHAR(36) NOT NULL COMMENT '所属用户意图周期标识，与 agent_run.intent_epoch 同源。采纳判定**只在本周期内进行**：跨周期的一律是新动作，否则用户真的要发第二条提醒时会被当成重试吞掉',
  `tool_name` VARCHAR(64) NOT NULL COMMENT '产生该副作用的工具名；采纳要求工具名相同',
  `args_fingerprint` CHAR(64) NOT NULL COMMENT '工具名与**归一化后**参数的SHA-256十六进制。它**参与采纳判定**（同周期+同工具+同指纹+创建于更早的步，四条同时满足才可采纳）与**漂移告警**，但**不是身份本身**——身份是随机的 effect_id。刻意不用参数哈希当身份：那会让"同义改写"和"合法改内容"两种情况都判错',
  `args_json` LONGTEXT NULL COMMENT '首次提出时的参数原文，用于漂移时的差异审计与人工排查；不保存凭据',
  `created_step_no` INT NOT NULL COMMENT '首次提出该副作用所在的模型步序号。采纳规则要求"创建于更早的 step"：同一批次里的两次相同调用是**两个有意的动作**（用户要发两条提醒），不该互相采纳',
  `external_id` VARCHAR(191) NULL COMMENT '远端返回的稳定业务标识；拿到它就等于拿到了对账句柄。长度 191 是为了在 utf8mb4 下可建索引',
  `status` VARCHAR(16) NOT NULL COMMENT '副作用生命周期：OPEN未确认完成(可被采纳)/SETTLED已有确认的invocation(不再采纳，否则会吞掉用户真的要做的第二次)/ABANDONED已放弃(如审批被拒)',
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '记录创建时间',
  `settled_at` DATETIME NULL COMMENT '进入SETTLED或ABANDONED的时间；OPEN期间为空',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_agent_effect_id` (`effect_id`),
  KEY `idx_agent_effect_adoption` (`intent_epoch`, `tool_name`, `status`),
  KEY `idx_agent_effect_run` (`run_id`),
  KEY `idx_agent_effect_user` (`user_id`),
  KEY `idx_agent_effect_conversation` (`conversation_id`),
  CONSTRAINT `fk_agent_effect_run` FOREIGN KEY (`run_id`) REFERENCES `agent_run` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_agent_effect_user` FOREIGN KEY (`user_id`) REFERENCES `sys_user` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_agent_effect_conversation` FOREIGN KEY (`conversation_id`) REFERENCES `agent_conversation` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='智能体逻辑副作用身份：一次业务动作可能对应多次物理调用';

CREATE TABLE IF NOT EXISTS `agent_approval` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '审批记录主键',
  `user_id` BIGINT NOT NULL COMMENT '审批所属用户ID，关联 sys_user.id',
  `conversation_id` BIGINT NOT NULL COMMENT '所属会话ID，关联 agent_conversation.id',
  `run_id` BIGINT NOT NULL COMMENT '所属执行记录ID，关联 agent_run.id',
  `invocation_db_id` BIGINT NOT NULL COMMENT '关联的工具调用日志主键，关联 agent_tool_invocation.id',
  `invocation_id` CHAR(36) NOT NULL COMMENT '工具调用稳定UUID，批准后继续使用且不重新生成',
  `tool_name` VARCHAR(64) NOT NULL COMMENT '等待审批的注册工具名称',
  `request_fingerprint` CHAR(64) NOT NULL COMMENT '工具名称与参数的SHA-256指纹，变更操作必须重新审批',
  `summary_json` LONGTEXT NOT NULL COMMENT '展示给所属用户的工具操作摘要JSON，不含凭据或原始提示词',
  `status` VARCHAR(24) NOT NULL COMMENT '审批状态：PENDING待决定/APPROVED已批准/REJECTED已拒绝',
  `decision_reason` VARCHAR(500) NULL COMMENT '用户拒绝或批准时填写的可选说明',
  `decided_at` DATETIME NULL COMMENT '用户作出审批决定的时间',
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '审批请求持久化时间',
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '审批记录最后更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_agent_approval_invocation` (`invocation_db_id`),
  KEY `idx_agent_approval_user_status` (`user_id`, `status`, `id`),
  KEY `idx_agent_approval_conversation` (`conversation_id`, `id`),
  CONSTRAINT `fk_agent_approval_user` FOREIGN KEY (`user_id`) REFERENCES `sys_user` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_agent_approval_conversation` FOREIGN KEY (`conversation_id`) REFERENCES `agent_conversation` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_agent_approval_run` FOREIGN KEY (`run_id`) REFERENCES `agent_run` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_agent_approval_invocation` FOREIGN KEY (`invocation_db_id`) REFERENCES `agent_tool_invocation` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='智能体高风险工具审批记录';
