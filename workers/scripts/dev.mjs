async function exists(path) {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

async function writeLocalVars(service, values) {
  const path = resolve(workspace, `services/${service.name}/.dev.vars`);
  if (await exists(path)) {
    const current = await readFile(path, "utf8");
    if (!current.startsWith(marker)) {
      throw new Error(`Refusing to overwrite existing local vars: ${path}`);
    }
    await unlink(path);
  }
  const body = `${marker}\n${Object.entries(values).map(([key, value]) => `${key}=${JSON.stringify(value)}`).join("\n")}\n`;
  await writeFile(path, body, { encoding: "utf8", flag: "wx" });
  createdFiles.push(path);
}

async function cleanup() {
  await Promise.all(children.map(async (child) => {
    if (child.exitCode !== null || !child.pid) return;
    if (process.platform !== "win32") {
      child.kill("SIGINT");
      return;
    }
    await new Promise((resolvePromise) => {
      const killer = spawn("taskkill.exe", ["/PID", String(child.pid), "/T", "/F"], {
        windowsHide: true,
        stdio: "ignore",
      });
      killer.once("error", () => {
        child.kill("SIGINT");
        resolvePromise();
      });
      killer.once("exit", () => resolvePromise());
    });
  }));
  for (const path of createdFiles) {
    try {
      await unlink(path);
    } catch {
      // A file already removed during shutdown needs no further action.
    }
  }
  for (const path of createdConfigs) {
    try {
      await unlink(path);
    } catch {
      // A generated config already removed during shutdown needs no further action.
    }
  }
}

async function localConfigFor(service) {
  const serviceDirectory = resolve(workspace, `services/${service.name}`);
  const sourcePath = resolve(serviceDirectory, "wrangler.jsonc");
  const config = JSON.parse(await readFile(sourcePath, "utf8"));
  let needsLocalConfig = false;

  // The local stack intentionally uses its explicit localhost URLs; service bindings are for same-account production calls.
  if (config.services?.length) {
    delete config.services;
    needsLocalConfig = true;
  }

  if (service.name === "gateway") {
    const serviceUrls = Object.fromEntries(services.slice(1).map((target) => {
      const key = target.name.toUpperCase().replaceAll("-", "_");
      return [`${key}_SERVICE_URL`, `http://127.0.0.1:${target.port}`];
    }));
    config.vars = {
      ...config.vars,
      ...serviceUrls,
      CORS_ALLOWED_ORIGINS: process.env.CORS_ALLOWED_ORIGINS
        || "http://localhost:3000,http://127.0.0.1:3000,http://localhost:5173,http://127.0.0.1:5173,https://dinqor.cn,https://xiaodongding.dpdns.org",
    };
    needsLocalConfig = true;
  }

  if (service.name === "agent") {
    // Wrangler only exposes .dev.vars keys declared by secrets.required when
    // the config has a secrets block. Keep optional model credentials local:
    // the production Agent uses Core-managed providers, while the local smoke
    // suite may inject a deterministic mock provider through the dev runner.
    if (process.env.AGENT_MODEL_API_KEY) {
      config.secrets = {
        ...config.secrets,
        required: [...new Set([
          ...(config.secrets?.required ?? []),
          ...agentModelEnvironmentKeys,
        ])],
      };
    }
    if (process.env.AGENT_IMAGE_MODEL_API_KEY) {
      config.secrets = {
        ...config.secrets,
        required: [...new Set([
          ...(config.secrets?.required ?? []),
          ...agentImageModelEnvironmentKeys,
        ])],
      };
    }
    if (agentOssSecretKeys.some((key) => process.env[key])) {
      config.secrets = {
        ...config.secrets,
        required: [...new Set([...(config.secrets?.required ?? []), ...agentOssSecretKeys])],
      };
    }
    if (agentMcpSecretEnvironmentKeys.some((key) => process.env[key])) {
      config.secrets = {
        ...config.secrets,
        required: [...new Set([...(config.secrets?.required ?? []), ...agentMcpSecretEnvironmentKeys])],
      };
    }
    if (process.env.AGENT_MCP_CLIENT_ENABLED === "true") {
      config.vars = { ...config.vars, AGENT_MCP_CLIENT_ENABLED: "true" };
    }
    if (process.env.AGENT_OSS_OBJECT_PREFIX) {
      config.vars = { ...config.vars, AGENT_OSS_OBJECT_PREFIX: process.env.AGENT_OSS_OBJECT_PREFIX };
    }
    needsLocalConfig = true;
  }

  if (service.name === "payment") {
    needsLocalConfig = true;
  }

  if (service.name === "platform-integration") {
    config.vars = {
      ...config.vars,
      MCP_OAUTH_PUBLIC_BASE_URL: "http://127.0.0.1:8787",
      ...(process.env.MCP_OAUTH_ENABLED ? { MCP_OAUTH_ENABLED: process.env.MCP_OAUTH_ENABLED } : {}),
      ...(process.env.PLATFORM_SELENIUM_URL ? { PLATFORM_SELENIUM_URL: process.env.PLATFORM_SELENIUM_URL } : {}),
      CONTENT_AUTOMATION_SERVICE_URL: `http://127.0.0.1:${services.find((target) => target.name === "content-automation").port}`,
      CORE_SERVICE_URL: `http://127.0.0.1:${services.find((target) => target.name === "core").port}`,
      ...Object.fromEntries(["MCP_BLOG_ENABLED", "MCP_CSDN_ENABLED", "MCP_DUAL_ENABLED", "MCP_JUEJIN_ENABLED"]
        .flatMap((key) => process.env[key] ? [[key, process.env[key]]] : [])),
    };
    needsLocalConfig = true;
  }

  if (service.name === "core") {
    config.vars = {
      ...config.vars,
      PLATFORM_INTEGRATION_SERVICE_URL: `http://127.0.0.1:${services.find((target) => target.name === "platform-integration").port}`,
      CONTENT_AUTOMATION_SERVICE_URL: `http://127.0.0.1:${services.find((target) => target.name === "content-automation").port}`,
      ...(process.env.ADMIN_MODEL_GATEWAY_ENABLED
        ? { ADMIN_MODEL_GATEWAY_ENABLED: process.env.ADMIN_MODEL_GATEWAY_ENABLED }
        : {}),
      ...Object.fromEntries(recitationEnvironmentKeys.flatMap((key) =>
        process.env[key] ? [[key, process.env[key]]] : [])),
      ...Object.fromEntries(refreshEnvironmentKeys.flatMap((key) =>
        process.env[key] ? [[key, process.env[key]]] : [])),
    };
    if ([...coreOssEnvironmentKeys, ...coreSecretEnvironmentKeys].some((key) => process.env[key])) {
      config.secrets = {
        ...config.secrets,
        required: [...new Set([
          ...(config.secrets?.required ?? []),
          ...coreOssEnvironmentKeys.filter((key) => process.env[key]),
          ...coreSecretEnvironmentKeys.filter((key) => process.env[key]),
        ])],
      };
    }
    needsLocalConfig = true;
  }

  if (service.name === "content-automation") {
    config.vars = {
      ...config.vars,
      ...(process.env.MAIL_FROM ? { MAIL_FROM: process.env.MAIL_FROM } : {}),
      ...(process.env.CONTENT_MEDIA_PUBLIC_BASE_URL || process.env.ALIYUN_OSS_BUCKET
        ? { CONTENT_MEDIA_PUBLIC_BASE_URL: process.env.CONTENT_MEDIA_PUBLIC_BASE_URL ?? `http://127.0.0.1:${services.find((target) => target.name === "content-automation").port}/api/public/blog/media` }
        : {}),
      ...Object.fromEntries(["CONTENT_OSS_PUBLIC_BASE_URL", "CONTENT_OSS_OBJECT_PREFIX", "CONTENT_MEDIA_OSS_OBJECT_PREFIX"]
        .flatMap((key) => process.env[key] ? [[key, process.env[key]]] : [])),
      PLATFORM_INTEGRATION_SERVICE_URL: `http://127.0.0.1:${services.find((target) => target.name === "platform-integration").port}`,
      CORE_SERVICE_URL: `http://127.0.0.1:${services.find((target) => target.name === "core").port}`,
    };
    const contentOssSecretKeys = contentOssEnvironmentKeys.filter((key) => key.startsWith("ALIYUN_OSS_"));
    if (contentOssSecretKeys.some((key) => process.env[key])) {
      config.secrets = {
        ...config.secrets,
        required: [...new Set([...(config.secrets?.required ?? []), ...contentOssSecretKeys.filter((key) => process.env[key])])],
      };
    }
    needsLocalConfig = true;
  }

  if (!needsLocalConfig) return "wrangler.jsonc";
  // A fixed wrangler.local.jsonc path can collide with a user's local override.
  // Give this run its own file and only remove the file this process created.
  const localPath = resolve(serviceDirectory, `.wrangler.local-${randomBytes(8).toString("hex")}.jsonc`);
  await writeFile(localPath, `${JSON.stringify(config, null, 2)}\n`, {
    encoding: "utf8",
    flag: "wx",
  });
  createdConfigs.push(localPath);
  return localPath;
}

async function waitForWorker(service) {
  const deadline = Date.now() + 30_000;
  while (Date.now() < deadline) {
    try {
      const response = await fetch(`http://127.0.0.1:${service.port}/healthz`, {
        signal: AbortSignal.timeout(1_000),
      });
      if (response.ok) return;
    } catch {
      // Wrangler is still compiling or opening the local port.
    }
    await new Promise((resolvePromise) => setTimeout(resolvePromise, 250));
  }
  throw new Error(`${service.name} did not become ready within 30 seconds.`);
}

async function applyLocalMigrations(service, pnpmEntry) {
  if (!service.databaseName) return;

  const serviceDirectory = resolve(workspace, `services/${service.name}`);
  const migrationDirectory = resolve(serviceDirectory, "migrations");
  const migrationFiles = (await readdir(migrationDirectory))
    .filter((file) => file.endsWith(".sql"));
  if (migrationFiles.length === 0) return;

  await new Promise((resolvePromise, rejectPromise) => {
    const child = spawn(process.execPath, [
      pnpmEntry,
      "exec",
      "wrangler",
      "d1",
      "migrations",
      "apply",
      service.databaseName,
      "--local",
      "--config",
      "wrangler.jsonc",
    ], {
      cwd: serviceDirectory,
      env: process.env,
      stdio: "inherit",
    });
    child.once("error", rejectPromise);
    child.once("exit", (code) => {
      if (code === 0) resolvePromise();
      else rejectPromise(new Error(`${service.name} D1 migration command exited with ${code ?? "unknown"}.`));
    });
  });
}

async function stop(exitCode = 0) {
  if (stopping) return;
  stopping = true;
  await cleanup();
  process.exitCode = exitCode;
}

