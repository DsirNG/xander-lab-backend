import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { parse } from "yaml";

const workspace = resolve(import.meta.dirname, "..");
const inventoryPath = resolve(workspace, "../docs/route-inventory.yaml");
const outputPath = resolve(workspace, "services/gateway/src/routes.generated.ts");
const policyPath = resolve(workspace, "../docs/auth-policy.yaml");
const policyOutputPath = resolve(workspace, "services/gateway/src/access-policy.generated.ts");
const ownerToService = {
  identity: "core",
  billing: "core",
  admin: "core",
  profile: "core",
  recitation: "core",
  agent: "agent",
  integration: "platform-integration",
  publishing: "content-automation",
  blogagent: "content-automation",
  automation: "content-automation",
  bloghtml: "bloghtml-preview",
  virtualpay: "payment",
};
const routeToService = {
  "admin-get-admin-virtual-pay-settings": "payment",
  "admin-put-admin-virtual-pay-settings": "payment",
};

const inventory = parse(await readFile(inventoryPath, "utf8"));
const policy = parse(await readFile(policyPath, "utf8"));
const rows = [];
for (const route of inventory.routes ?? []) {
  const service = routeToService[route.id] ?? ownerToService[route.logical_owner];
  const path = route.path;
  if (!service || typeof path !== "string") continue;
  if (path.startsWith("/internal/") || path.startsWith("/api/internal/")) continue;

  rows.push({
    method: String(route.http_method ?? "ANY").toUpperCase(),
    path,
    service,
  });
}

const unique = new Map();
for (const route of rows) {
  const key = `${route.method} ${route.path}`;
  const current = unique.get(key);
  if (current && current.service !== route.service) {
    throw new Error(`Gateway route has multiple owners: ${key} -> ${current.service}, ${route.service}`);
  }
  unique.set(key, route);
}

const routes = [...unique.values()].sort((left, right) => {
  const specificity = (route) => route.path
    .replace(/\{[^}]+\}/g, "")
    .replace(/\*+/g, "")
    .length;
  return specificity(right) - specificity(left)
    || Number(left.method === "ANY") - Number(right.method === "ANY")
    || left.path.localeCompare(right.path);
});

const content = [
  "// Generated from docs/route-inventory.yaml by scripts/generate-routes.mjs.",
  "// Do not edit this file directly; internal-only and excluded domains are filtered by the generator.",
  "export const ROUTES =",
  `${JSON.stringify(routes, null, 2)} as const;`,
  "",
].join("\n");

const policyGroups = [
  "preflight",
  "excluded",
  "prefix_rules",
  "explicit_private_get",
  "explicit_public_write",
  "public_get",
  "public_non_api",
  "streams",
  "protected",
];
const accessPolicy = Object.fromEntries(policyGroups.map((group) => [group, policy[group] ?? []]));
accessPolicy.default = policy.default;
const policyContent = [
  "// Generated from docs/auth-policy.yaml by scripts/generate-routes.mjs.",
  "// Do not edit this file directly; auth-policy.yaml is the single source of truth.",
  "export const ACCESS_POLICY =",
  `${JSON.stringify(accessPolicy, null, 2)} as const;`,
  "",
].join("\n");

if (process.argv.includes("--check")) {
  let existing = "";
  try {
    existing = await readFile(outputPath, "utf8");
  } catch {
    // A missing generated file is reported by the same stale-output error below.
  }
  if (existing !== content) {
    console.error("Gateway route manifest is stale. Run `pnpm generate:routes`.");
    process.exitCode = 1;
  }
  let existingPolicy = "";
  try {
    existingPolicy = await readFile(policyOutputPath, "utf8");
  } catch {
    // A missing generated policy uses the same stale-output error below.
  }
  if (existingPolicy !== policyContent) {
    console.error("Gateway access policy is stale. Run `pnpm generate:routes`.");
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, content, "utf8");
  await writeFile(policyOutputPath, policyContent, "utf8");
  console.log(`Generated ${routes.length} public routes for the Worker Gateway.`);
}
