package com.xander.lab.agent.application;

import java.util.List;

/**
 * 运行期才知道有哪些工具的来源。
 *
 * <p>内置工具都是 {@code @Component}，启动期就被 {@link AgentToolRegistry} 一次收齐。
 * 但有一类工具的存在取决于配置：接了哪几台远端 MCP 服务器、对方提供了哪些工具，
 * 都要读配置才知道。这类来源走本接口，由注册表在合并视图时拉取。</p>
 *
 * <p><b>实现必须廉价。</b>注册表每一轮渲染工具面都会读一次，实现内部要自己缓存；
 * 不能每次调用都去连远端或查库——那会把每一轮模型调用都变成一次网络往返。</p>
 */
public interface AgentDynamicToolSource {

    /**
     * 该用户可用的动态工具。
     *
     * <p>动态工具是有归属的：平台级配置人人可用，用户自己配的只能自己用。
     * 所以这里带 userId 而不是返回一份全局列表——否则甲的服务器会出现在乙的工具面里。</p>
     *
     * @param userId 归属用户；{@code null} 表示不限定用户，返回全部动态工具
     *               （用于 {@code names()} 这类不区分用户的场景）
     */
    List<AgentTool> dynamicTools(Long userId);

    /**
     * 来源的版本号：工具集合一变，这个值就必须变。{@code 0} 表示"永不变"。
     *
     * <h2>为什么需要它</h2>
     * <p>注册表缓存的是"内置 + 动态"的合并视图，而合并视图必须逐字节稳定（同一轮里主调用
     * 与摘要调用各渲染一次，只有两次一致，摘要请求才是主请求的真前缀）。所以缓存不能省。
     * 那么配置变更之后谁来让缓存失效？</p>
     *
     * <p>一个显然的做法是"来源方反向调 {@code AgentToolRegistry#invalidate()}"。它在单进程里
     * 能用，但它要求<b>提供方依赖消费方的实现类</b>——MCP 客户端在 integration 域，注册表在
     * agent 域，拆服务之后这就是一条反向的跨服务依赖。改成消费方读版本号之后，控制流只剩一个
     * 方向：注册表问，来源答，来源永远不需要知道注册表是谁。</p>
     *
     * <h2>契约</h2>
     * <ul>
     *   <li><b>单调不减。</b>版本可以跳（+1、+100 都行），但不能变小。</li>
     *   <li><b>必须廉价。</b>每次渲染工具面都会被读，一个 volatile long 或 AtomicLong 就好，
     *       不许查库、不许发请求。</li>
     *   <li><b>返回 0 表示这个来源永不变化</b>，注册表就只在显式 {@code invalidate()} 时重建。
     *       这是默认值，也正是加它之前的行为——所以既有的 lambda 实现一个都不用改。</li>
     * </ul>
     *
     * <p><b>⚠️ 注册表必须在调 {@link #dynamicTools(Long)} 之前先读版本。</b>顺序反了会留下
     * 一个永久性的陈旧缓存：先取工具（旧）、再读版本（新），于是"新版本 + 旧工具"被存下来，
     * 版本再也不会变，那份旧工具就再也刷新不掉了。由 {@code AgentToolRegistryTest} 用调用顺序
     * 断言钉住——它没有任何别的症状。</p>
     *
     * <p>为什么是 {@code default} 而不是抽象方法：本接口是<b>函数式接口</b>，测试里大量用
     * lambda 实现它（{@code setDynamicToolSources(List.of(userId -> ...))}）。加一个抽象方法
     * 会让那些 lambda 全部编译不过，而它们表达的正是"版本恒为 0 的静态来源"这个合法语义。
     * 默认值 {@code 0} 恰好就是那个语义，所以这里用 {@code default} 是对的——它不是"静默变宽"，
     * 而是"给一个语义正确的默认值"。</p>
     */
    default long version() {
        return 0L;
    }
}
