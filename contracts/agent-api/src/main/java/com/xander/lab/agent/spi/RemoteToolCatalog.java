package com.xander.lab.agent.spi;

import java.util.List;

/**
 * 一个"运行期才知道有哪些工具"的来源。agent 是消费方，integration 是提供方。
 *
 * <h2>为什么这个接口住在 agent 这一侧</h2>
 * <p>跨域必须走<b>消费方拥有的契约</b>。这里的消费方是 agent——是它需要"这个用户
 * 能看到哪些远端工具"，也是它定下工具长什么样；提供方是 integration 的 MCP 客户端。
 * 所以端口随消费方走，和 {@code content.api.BlogPublisher} 完全同形：内容域定义"把这段
 * 内容推到那个平台"，integration 域实现它。</p>
 *
 * <p>住在提供方一侧（比如 {@code integration.api}）在数字上也能让那条边消失，但方向是反的：
 * 消费方会依赖提供方的发布节奏与内部形状，提供方一动消费方就得跟着动。判据不是"名字看起来
 * 属于谁"，而是"谁提问"。</p>
 *
 * <h2>调用契约</h2>
 * <p><b>实现必须廉价。</b>消费方每一轮渲染工具面都会读一次，实现内部要自己缓存；不能每次
 * 调用都去连远端或查库——那会把每一轮模型调用都变成一次网络往返。</p>
 *
 * <p>取不到工具时<b>返回空列表，不要抛异常</b>：少几个工具对话照常，一次远端抖动不该让
 * 整轮对话失败。（消费方也会兜住异常，但那不该是提供方偷懒的理由。）</p>
 *
 * <h2>为什么有 {@link #catalogVersion()} 而不是一个 {@code invalidate()} 回调</h2>
 * <p>如果让提供方在配置变更后反过来调消费方
 * {@code AgentToolRegistry#invalidate()}。这条反向依赖必须去掉：integration 不该调 agent
 * 的实现类。改成消费方读提供方的版本号之后，控制流只剩一个方向——消费方问，提供方答，
 * 提供方永远不需要知道消费方是谁。这和 {@code version}/{@code etag} 是同一个套路：把
 * "我变了"的通知换成"你问我变没变"的轮询，代价是每次多读一个 {@code long}。</p>
 */
public interface RemoteToolCatalog {

    /**
     * 该用户可用的远端工具。
     *
     * <p>动态工具是有归属的：平台级配置人人可用，用户自己配的只能自己用。所以这里带
     * userId 而不是返回一份全局列表——否则甲的服务器会出现在乙的工具面里。</p>
     *
     * <p>返回顺序不参与契约：消费方会按工具名重排，保证同一套工具每轮渲染出的提示词前缀
     * 逐字节一致（上游 prompt 缓存靠这个）。重复名字由消费方按 {@code putIfAbsent} 去重。</p>
     *
     * @param userId 归属用户；{@code null} 表示不限定用户，返回全部工具
     *               （用于 {@code names()} 这类不区分用户的场景）
     */
    List<RemoteTool> tools(Long userId);

    /**
     * 工具目录的版本号：目录内容一变，这个值就必须变。{@code 0} 表示"永不变"。
     *
     * <p><b>必须单调不减，且必须廉价</b>（一个 volatile long 或 AtomicLong，不许查库、不许
     * 发请求）——消费方每次渲染工具面都会读它。</p>
     *
     * <p><b>⚠️ 消费方必须在取 {@link #tools(Long)} 之前先读版本。</b>顺序反了会留下一个
     * 永久性的陈旧缓存：先取工具（旧）、再读版本（新），于是"新版本 + 旧工具"被存下来，
     * 版本再也不会变，那份旧工具就再也刷新不掉了。这个顺序由
     * {@code AgentToolRegistryTest} 用调用顺序断言钉住——它没有任何别的症状。</p>
     *
     * <p>反过来（先读版本、后取工具）总是安全的：期间发生的变更会让读到的版本偏旧，缓存
     * 被判为过期并重建，最多多刷一次。</p>
     */
    long catalogVersion();
}
