#!/usr/bin/env python3
"""Audit the 80 historical SQL scripts before Flyway baseline (V9 section 64).

V9 section 64 step 3 requires a historical audit covering:
  - naked ALTER            (no IF EXISTS / IF NOT EXISTS guard)
  - CREATE without IF NOT EXISTS
  - DROP without IF EXISTS
  - multi-writer tables    (the same table mutated by several scripts)
  - comment / dictionary changes

Output: migrations/legacy/AUDIT.md + migrations/legacy/SHA256SUMS
"""

from __future__ import annotations

import hashlib
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import scan  # noqa: E402

DB_DIR = scan.REPO / "src" / "main" / "resources" / "db"
LEGACY_DIR = scan.REPO / "migrations" / "legacy"

CREATE_RE = re.compile(r"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?`?(\w+)`?", re.IGNORECASE)
CREATE_UNGARDED_RE = re.compile(r"CREATE\s+TABLE\s+(?!IF\s+NOT\s+EXISTS)`?(\w+)`?", re.IGNORECASE)
ALTER_RE = re.compile(r"ALTER\s+TABLE\s+`?(\w+)`?", re.IGNORECASE)
ALTER_NAKED_ADD_RE = re.compile(
    r"ALTER\s+TABLE\s+`?(\w+)`?[^;]*?ADD\s+(?:COLUMN\s+)?(?!IF\s+NOT\s+EXISTS)",
    re.IGNORECASE | re.DOTALL)
ADD_COLUMN_RE = re.compile(
    r"ADD\s+COLUMN\s+(?:IF\s+NOT\s+EXISTS\s+)?`?(\w+)`?", re.IGNORECASE)
DROP_RE = re.compile(r"DROP\s+(TABLE|INDEX|COLUMN)\s+(?:IF\s+EXISTS\s+)?`?(\w+)`?",
                     re.IGNORECASE)
DROP_UNGARDED_RE = re.compile(r"DROP\s+(TABLE|INDEX|COLUMN)\s+(?!IF\s+EXISTS)", re.IGNORECASE)
MODIFY_RE = re.compile(r"MODIFY\s+(?:COLUMN\s+)?`?(\w+)`?", re.IGNORECASE)
COMMENT_RE = re.compile(r"COMMENT\s+'", re.IGNORECASE)
DELIMITER_RE = re.compile(r"DELIMITER|CREATE\s+PROCEDURE|CREATE\s+TRIGGER", re.IGNORECASE)
AUTOCOMMIT_RE = re.compile(r"\b(COMMIT|ROLLBACK|SET\s+AUTOCOMMIT)\b", re.IGNORECASE)


def audit() -> dict:
    scripts = sorted(DB_DIR.glob("*.sql"))
    writers: dict[str, list[str]] = defaultdict(list)
    columns_added: dict[str, list[str]] = defaultdict(list)
    per_file: list[dict] = []

    for path in scripts:
        raw = path.read_text(encoding="utf-8", errors="replace")
        body = scan.strip_sql_comments(raw)
        entry = {
            "file": path.name,
            "sha256": hashlib.sha256(raw.encode("utf-8")).hexdigest(),
            "bytes": len(raw.encode("utf-8")),
            "creates": CREATE_RE.findall(body),
            "creates_unguarded": CREATE_UNGARDED_RE.findall(body),
            "alters": ALTER_RE.findall(body),
            "alters_naked": ALTER_NAKED_ADD_RE.findall(body),
            "drops_unguarded": len(DROP_UNGARDED_RE.findall(body)),
            "drop_targets": [f"{kind}:{name}" for kind, name in DROP_RE.findall(body)],
            "modifies": MODIFY_RE.findall(body),
            "comments": len(COMMENT_RE.findall(body)),
            "procedural": bool(DELIMITER_RE.search(body)),
            "autocommit": bool(AUTOCOMMIT_RE.search(body)),
        }
        for table in entry["creates"] + entry["alters"]:
            writers[table].append(path.name)
        for table, column in re.findall(
                r"ALTER\s+TABLE\s+`?(\w+)`?[^;]*?ADD\s+COLUMN\s+(?:IF\s+NOT\s+EXISTS\s+)?`?(\w+)`?",
                body, re.IGNORECASE | re.DOTALL):
            columns_added[table].append(f"{column} ({path.name})")
        per_file.append(entry)

    return {
        "scripts": per_file,
        "multi_writer": {t: sorted(set(f)) for t, f in writers.items() if len(set(f)) > 1},
        "duplicate_columns": {
            t: cols for t, cols in columns_added.items()
            if len(cols) != len(set(cols))
        },
    }


def render(result: dict) -> str:
    scripts = result["scripts"]
    unguarded_creates = [s for s in scripts if s["creates_unguarded"]]
    naked_alters = [s for s in scripts if s["alters_naked"]]
    unguarded_drops = [s for s in scripts if s["drops_unguarded"]]
    procedural = [s for s in scripts if s["procedural"]]
    autocommit = [s for s in scripts if s["autocommit"]]
    comment_scripts = [s for s in scripts if s["comments"]]
    multi = result["multi_writer"]
    dup_cols = result["duplicate_columns"]

    lines = [
        "# Legacy SQL audit (V9 §64 step 3)",
        "",
        "Generated by `scripts/migration/audit_legacy_sql.py`.",
        "Scope: the 80 historical scripts under `src/main/resources/db/`.",
        "These scripts are **archived, not replayed** — Flyway baselines the current",
        "production schema and new changes start from `V2026091500`.",
        "",
        "## Summary",
        "",
        f"- scripts: **{len(scripts)}**",
        f"- `CREATE TABLE` without `IF NOT EXISTS`: **{len(unguarded_creates)}** scripts",
        f"- naked `ALTER TABLE ... ADD` without `IF NOT EXISTS`: **{len(naked_alters)}** scripts",
        f"- `DROP` without `IF EXISTS`: **{len(unguarded_drops)}** scripts",
        f"- tables written by more than one script: **{len(multi)}**",
        f"- scripts with duplicate `ADD COLUMN` of the same name: **{len(dup_cols)}**",
        f"- scripts containing `DELIMITER` / procedure / trigger: **{len(procedural)}**",
        f"- scripts containing `COMMIT` / `ROLLBACK` / `SET AUTOCOMMIT`: **{len(autocommit)}**",
        f"- scripts carrying `COMMENT` changes: **{len(comment_scripts)}**",
        "",
        "## Why this matters for the baseline",
        "",
        "1. **Unguarded `CREATE TABLE` / naked `ALTER`** — these scripts were written to be",
        "   run once by hand. Replaying them (or feeding them to Flyway as-is) fails on an",
        "   existing database, which is exactly why §64 forbids stuffing them into Flyway.",
        "2. **Multi-writer tables** — several scripts mutate the same table, so there is no",
        "   single authoritative DDL for it. The baseline must be taken from the **live",
        "   production schema** (`mysqldump --no-data`), not reconstructed from these files.",
        "3. **Duplicate `ADD COLUMN`** — the same column is added by more than one script;",
        "   only the live schema tells us which one actually applied.",
        "4. **`COMMIT` / `ROLLBACK` / `DELIMITER` inside migration files** — Flyway runs each",
        "   migration in its own transaction (MySQL DDL is auto-committing anyway). Any",
        "   historical script containing these must never be promoted into `versioned/`.",
        "",
        "## Findings",
        "",
    ]

    def section(title: str, items: list, formatter) -> None:
        lines.append(f"### {title}")
        lines.append("")
        if not items:
            lines.append("- none")
            lines.append("")
            return
        for item in items:
            lines.append(formatter(item))
        lines.append("")

    section("`CREATE TABLE` without `IF NOT EXISTS`", unguarded_creates,
            lambda s: f"- `{s['file']}` → {', '.join(s['creates_unguarded'])}")
    section("Naked `ALTER TABLE ... ADD`", naked_alters,
            lambda s: f"- `{s['file']}` → {', '.join(s['alters_naked'])}")
    section("`DROP` without `IF EXISTS`", unguarded_drops,
            lambda s: f"- `{s['file']}` → {s['drops_unguarded']} occurrence(s); "
                      f"targets: {', '.join(s['drop_targets']) or 'n/a'}")
    section("Tables written by more than one script", sorted(multi.items()),
            lambda item: f"- `{item[0]}` ← {', '.join(item[1])}")
    section("Duplicate `ADD COLUMN`", sorted(dup_cols.items()),
            lambda item: f"- `{item[0]}`: {', '.join(item[1])}")
    section("Procedural SQL (`DELIMITER` / procedure / trigger)", procedural,
            lambda s: f"- `{s['file']}`")
    section("Transaction control inside the script", autocommit,
            lambda s: f"- `{s['file']}`")

    lines += [
        "## Baseline procedure (Wave 0A)",
        "",
        "```text",
        "1. mysqldump --no-data --skip-comments xander_lab > migrations/legacy/baseline-schema.sql",
        "   (snapshot only — used to diff future drift; NOT executed by Flyway)",
        "2. flyway baseline -baselineVersion=2026091500 -baselineDescription=pre-microservices \\",
        "        -url=jdbc:mysql://<host>/xander_lab -user=dinqor_migration",
        "3. flyway migrate  → applies V2026091501 ... in order",
        "4. business services run with spring.flyway.enabled=false",
        "```",
        "",
        "Applied migrations must never be edited: Flyway validates checksums on every run.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    result = audit()
    LEGACY_DIR.mkdir(parents=True, exist_ok=True)

    (LEGACY_DIR / "AUDIT.md").write_text(render(result), encoding="utf-8", newline="\n")

    sums = "".join(f"{s['sha256']}  {s['file']}\n" for s in result["scripts"])
    (LEGACY_DIR / "SHA256SUMS").write_text(sums, encoding="utf-8", newline="\n")

    print(f"wrote migrations/legacy/AUDIT.md ({len(result['scripts'])} scripts)")
    print(f"wrote migrations/legacy/SHA256SUMS")
    print(f"  unguarded CREATE TABLE : {sum(1 for s in result['scripts'] if s['creates_unguarded'])}")
    print(f"  naked ALTER ... ADD    : {sum(1 for s in result['scripts'] if s['alters_naked'])}")
    print(f"  unguarded DROP         : {sum(1 for s in result['scripts'] if s['drops_unguarded'])}")
    print(f"  multi-writer tables    : {len(result['multi_writer'])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
